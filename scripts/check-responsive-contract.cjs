const assert=require("node:assert/strict");
const fs=require("node:fs");
const css=fs.readFileSync("app/globals.css","utf8");
const finder=fs.readFileSync("components/GuidePlaceFinder.module.css","utf8");
const map=fs.readFileSync("components/MapApp.tsx","utf8");
assert.match(css,/@media\(max-width:900px\)/,"Mobile breakpoint missing");
assert.match(css,/100dvh/,"Dynamic mobile viewport support missing");
assert.match(css,/min-height:44px/,"Mobile tap targets missing");
assert.match(css,/font-size:16px/,"Mobile input font zoom prevention missing");
assert.match(css,/:focus-visible/,"Keyboard focus indicator missing");
assert.match(css,/prefers-reduced-motion:reduce/,"Reduced-motion accessibility missing");
assert.match(css,/overscroll-behavior:contain/,"Mobile detail scrolling isolation missing");
assert.match(finder,/@media/,"Guide finder responsive styling missing");
assert.match(map,/mapError/,"Map error fallback missing");
assert.match(map,/aria-modal="true"/,"Report dialog must be announced as modal");
assert.match(map,/aria-labelledby="report-dialog-title"/,"Report dialog must have an accessible name");
assert.match(map,/dialogCloseRef\.current\?\.focus\(\)/,"Dialog must receive keyboard focus");
assert.match(map,/event\.key==="Escape"/,"Escape must close dialog");
assert.match(map,/dialogPreviousFocus\.current\?\.focus\(\)/,"Focus must return after dialog closes");
assert.match(map,/if\(reportSubmitting\.current\)return/,"Duplicate report requests must be blocked");
assert.match(map,/finally\{reportSubmitting\.current=false\}/,"Report submission lock must release after failure or success");
assert.match(map,/role="status" aria-live="polite"/,"Report result should be announced to assistive technology");
const submissions=fs.readFileSync("app/api/submissions/route.ts","utf8");
assert.match(submissions,/Array\.isArray\(parsed\)/,"Submission API must reject JSON arrays");
assert.match(submissions,/施設IDを確認してください/,"Submission API must validate place IDs");
assert.match(submissions,/メールアドレスを確認してください/,"Submission API must validate optional email");
assert.match(submissions,/catch\{return NextResponse\.json\(\{error:"送信できませんでした。時間をおいて再度お試しください。"/,"Submission DB exceptions must return controlled errors");
assert.match(submissions,/typeof b\.place_id==="number"/,"Submission IDs must reject non-string non-number inputs");
assert.match(submissions,/typeof b\.evidence_url!=="string"/,"Evidence URLs must reject non-string values");
assert.match(submissions,/typeof b\.contact_email!=="string"/,"Contact emails must reject non-string values");
assert.match(submissions,/\["prefecture_name","address","note"\]/,"Optional submission text fields must be validated");
assert.match(submissions,/\^\[1-9\]/,"Submission IDs must use a strict positive digit pattern");
assert.match(submissions,/Number\.isSafeInteger\(rawId\)/,"Submission IDs must be safe integers");
assert.match(submissions,/submission_type!=="add"&&place_id===null/,"Updates and closures must reference a facility");
assert.match(submissions,/try\{const db=createClient\(url,key\)/,"Submission database client initialization must be protected");
assert.ok(submissions.includes('["submission_type","category_slug","name"].some'),"Required submission fields must be strings");
console.log("Responsive CSS and accessibility contracts passed");

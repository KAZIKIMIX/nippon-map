const assert=require("node:assert/strict");
const fs=require("node:fs");
const read=path=>fs.readFileSync(path,"utf8");
const map=read("components/MapApp.tsx");
const finder=read("components/GuidePlaceFinder.tsx");
const pref=read("components/PrefectureMap.tsx");
const detail=read("app/guides/[category]/[prefecture]/page.tsx");
const data=read("lib/guide-data.ts");
const share=read("lib/map-share.ts");
assert.match(map,/readSharedMap\(window\.location\.search/,"Map deep links must restore filters");
assert.match(map,/pendingSharedPlace\.current=state\.placeId/,"Map deep links must restore selected place");
assert.match(map,/createSharedMapUrl\(/,"Map share must preserve state");
assert.match(map,/normalize\("NFKC"\)/,"Map search must normalize full-width characters");
assert.match(map,/p\.address/,"Map search must include address");
assert.match(map,/setResultLimit\(8\)/,"Map search result pagination must reset");
assert.match(finder,/setVisibleLimit\(40\)/,"Guide pagination must reset on filters");
assert.ok(finder.includes('if(query.trim())mapParams.set("q",query.trim())')&&finder.includes('if(city)mapParams.set("city",city)'),"Guide must retain both keyword and municipality");
assert.ok(map.includes('setCityFilter(state.city||"")')&&map.includes('p.municipality_name===cityFilter'),"Map must restore and apply municipality filter");
assert.ok(share.includes('params.get("city")')&&share.includes('url.searchParams.set("city"'),"Shared URLs must preserve municipality");
assert.ok(finder.includes('setCity("")')&&finder.includes('setQuery("")')&&finder.includes('setSort("name")'),"Clear filters must restore defaults");
assert.match(finder,/new URLSearchParams\(\{category,prefecture,place:String\(p\.id\)\}\)/,"Guide place links must retain filters");
assert.match(pref,/setRegion\("all"\)/,"Map reset must restore national view");
assert.match(pref,/setRetry\(n=>n\+1\)/,"Failed map should support retry");
assert.match(pref,/prefectureOrder\.slice\(39\)/,"Kyushu should include Fukuoka");
assert.match(detail,/getGuidePlaces\(category,name\)/,"Prefecture guide should query only selected prefecture");
assert.match(data,/p_prefecture_name:prefecture/,"Database query must filter prefecture");
assert.ok(share.includes("prefecture")&&share.includes("place"),"Share module must preserve prefecture and place");
assert.ok(map.includes('setQ(e.target.value);setCityFilter("");setSelected(null)'),"Editing map search must clear hidden municipality filter");
assert.ok(map.includes('setQ("");setCityFilter("");setSelected(null)'),"Clearing map search must clear municipality filter");
assert.ok(map.includes("if(!loaded||!pendingSharedPlace.current||!cat)return;"),"Shared place restoration must finish on empty or failed category loads");
assert.ok(map.includes("if(!r.ok)throw new Error(`Places request failed: ${r.status}`)"),"Map places loader must reject HTTP error responses");
assert.ok(map.includes("[cat,prefecture,placesRetry]")&&map.includes("setPlacesRetry(n=>n+1)"),"Failed place loads must have a working retry action");
const photoApi=read("app/api/place-photo/route.ts");
const detailsApi=read("app/api/place-details/route.ts");
assert.ok(share.includes("prefectures.has(state.prefecture)"),"Shared map URL must reject invalid prefectures");
assert.ok(share.includes("\\d{0,14}"),"Shared map IDs must have a length bound");
assert.ok(photoApi.includes(".trim().slice(0,160)"),"Photo lookup names must be bounded");
assert.ok(detailsApi.includes("coordinate_note.slice(0,500)"),"Railway coordinate notes must be bounded");
assert.ok(detailsApi.includes(".map(x=>x.slice(0,160))"),"Railway route labels must be bounded");
assert.ok(share.includes("state.placeId <= 999999999999999"),"Generated shared place IDs must match accepted length");
assert.ok(detailsApi.includes("catch{return NextResponse.json({details:null},{status:503})}"),"Place details must handle database exceptions");
assert.ok(detailsApi.includes("x.trim().length>0")&&detailsApi.includes("x.trim().slice(0,160)"),"Railway metadata must omit empty labels and trim whitespace");
console.log("Map and guide state contract checks passed");
